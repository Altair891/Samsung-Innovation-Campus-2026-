"""### ⚠️ What NOT To Do: Broken Indentation

Below is an example of **incorrect indentation** (shown as text, not run, so it doesn't break our notebook). In Python, this would raise an `IndentationError`:

```python
if 5 > 2:
print("Five is greater than two")   # ❌ Error! This line needs to be indented
```

Python expects the code **inside** the `if` block to be indented consistently (usually 4 spaces). Let's see the **correct** version in the next cell. ✅

"""

# Correct indentation - the line inside the "if" block is indented with 4 spaces
if 5 > 2:
  print("Five is greater than two")  # ✅ This works!

"""## 5️⃣ Comments & Code Readability 💬

Comments start with `#` and are ignored by Python when the code runs. They're notes **for humans**, not the computer. Good comments explain *why* something is done, not just *what* (the code already shows *what*).

"""

