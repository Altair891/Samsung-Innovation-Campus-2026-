# Mengambil data pengiriman dari pengguna
berat_paket = float(input("Masukkan berat paket (kg): "))
zona = input("Masukkan zona pengiriman (dalam kota / luar kota / luar pulau): ").strip().lower()
jenis_layanan = input("Masukkan jenis layanan (reguler / express): ").strip().lower()

# Menentukan tarif dasar per kg berdasarkan zona tujuan (percabangan 1)
if zona == "dalam kota":
    tarif_dasar = 8000
elif zona == "luar kota":
    tarif_dasar = 15000
elif zona == "luar pulau":
    tarif_dasar = 30000
else:
    tarif_dasar = 0
    print("Zona pengiriman tidak dikenal.")

if tarif_dasar > 0:
    # Menghitung total ongkir awal berdasarkan berat
    total_ongkir = berat_paket * tarif_dasar

    # Menambahkan biaya tambahan jika memilih layanan express (percabangan 2)
    if jenis_layanan == "express":
        total_ongkir += 10000

    # Memberikan potongan diskon jika berat > 10 kg ATAU pengiriman luar pulau menggunakan express (operator logika 'or')
    if berat_paket > 10 or (zona == "luar pulau" and jenis_layanan == "express"):
        diskon = 0.10 * total_ongkir
        total_ongkir -= diskon
