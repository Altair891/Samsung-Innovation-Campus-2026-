"""<a id="11"></a>
## 11. Studi Kasus: Loop di Dunia Nyata (IoT & AI)

### 🌡️ Sensor IoT
Alat pemantau suhu di dunia nyata terus membaca data setiap beberapa detik menggunakan `while True`. Supaya notebook ini tidak berjalan selamanya, kita simulasikan dengan **batas jumlah pembacaan** memakai `while` + `break`.
"""

import random

jumlah_bacaan = 0
batas_bacaan = 5  # simulasi: sensor kita batasi baca 5 kali saja

while True:
    suhu = round(random.uniform(24.0, 32.0), 1)
    print(f"Bacaan ke-{jumlah_bacaan + 1} -> Suhu: {suhu}°C")
    jumlah_bacaan += 1
    if jumlah_bacaan >= batas_bacaan:
        print("Simulasi selesai, sensor berhenti membaca.")
        break

"""### 🤖 Melatih Model AI
Model AI belajar dengan mengulang proses training berkali-kali — tiap putaran disebut satu **epoch**. Di bawah ini kita simulasikan *loss* (tingkat kesalahan model) yang semakin mengecil setiap epoch.
"""

jumlah_epoch = 10
loss = 1.0  # loss awal (semakin kecil semakin bagus)

for epoch in range(1, jumlah_epoch + 1):
    loss = loss * 0.8  # setiap epoch, loss berkurang 20%
    print(f"Epoch {epoch}/{jumlah_epoch} -> loss: {loss:.4f}")

print("Training selesai!")

