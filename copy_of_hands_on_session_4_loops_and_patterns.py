"""<a id="3"></a>
## 3. `while` Loop

`while` dipakai saat jumlah pengulangan **belum pasti**, tergantung sebuah syarat yang bisa berubah.

### Anatomi sebuah `while` loop

```python
i = 0
while i < 5:
    print(i)
    i += 1
```

| Bagian | Penjelasan |
|---|---|
| `i = 0` | nilai awal, disiapkan sebelum loop dimulai |
| `while i < 5` | syarat yang dicek setiap kali sebelum satu putaran dijalankan |
| `print(i)` | badan loop, dijalankan selama syarat masih `True` |
| `i += 1` | update variabel — **WAJIB ada**, agar suatu saat syaratnya jadi `False` |

⚠️ Kalau kita lupa menulis baris update (`i += 1`), loop akan berjalan **selamanya** (disebut *infinite loop*)!
"""

i = 0
while i < 5:
    print(i)
    i += 0.5

baterai = 100
while baterai > 0:
    print("Baterai:", baterai)
    baterai -= 20

