"""<a id="5"></a>
## 5. `continue` — Melompati Iterasi

`continue` hanya melompati langkah saat ini, lalu **lanjut** ke iterasi berikutnya — beda dengan `break` yang berhenti total.
"""

for angka in range(0, 10):
    if angka == 3:
        continue
    print(angka)

# output: 1  2  4
# angka 3 dilewati, tapi loop tetap lanjut sampai selesai

for angka in range(0, 10):
    if angka%2 == 1: #skip angka ganjil
        continue
    print(angka)

"""### Ringkasan `break` vs `continue`

| | `break` | `continue` |
|---|---|---|
| Efek | Menghentikan loop sepenuhnya | Hanya melompati iterasi saat ini |
| Sisa iterasi | Tidak dijalankan lagi | Loop tetap lanjut ke putaran berikutnya |
| Ibarat | "Berhenti total, langsung keluar" | "Skip dulu, tapi tetap jalan terus" |
| Cocok untuk | Berhenti begitu sudah ketemu yang dicari | Melewati data yang tidak relevan |

### 📝 Latihan 4
Cetak hanya bilangan **ganjil** dari 1 sampai 20 menggunakan `for` dan `continue`.
"""

