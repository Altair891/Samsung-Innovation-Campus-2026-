"""## 2️⃣ Data Types Overview 🔤🔢

Every value in Python has a **type**. The four most common beginner types are:

- 🔢 **`int`** — whole numbers, e.g. `5`, `-3`, `100`
- 🌊 **`float`** — decimal numbers, e.g. `3.14`, `-0.5`
- 🔤 **`str`** — text (strings), written in quotes, e.g. `"hello"`
- ✅ **`bool`** — `True` or `False` values

You can check any value's type using the built-in `type()` function.

"""

