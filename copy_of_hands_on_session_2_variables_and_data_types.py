"""## 3️⃣ Type Conversion 🔄

Sometimes you need to convert a value from one type to another. Python gives us handy functions for this:

- `int()` → convert to a whole number
- `float()` → convert to a decimal number
- `str()` → convert to text

Let's see some examples, including a **common mistake** beginners make.

"""

