"""### ⚠️ Common Mistake: Mixing Types

You **cannot** directly combine a string and a number with `+`. Python doesn't know if you mean "add them like numbers" or "join them like text," so it raises a `TypeError`.

Run the cell below to see the error in action (this is expected!):

"""

# ❌ Broken example - this will raise a TypeError
age = 25
message = "My age is: " + age
print(message)

"""👆 That error happens because `age` is an `int`, and you can't `+` it directly to a `str`. To fix it, convert `age` to a string first using `str()`:

"""

# ✅ Corrected version - convert age to a string first
age = 25
message = "My age is: " + str(age)
print(message)

