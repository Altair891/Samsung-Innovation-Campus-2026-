"""## Soal 6 — Set: Peserta Unik 👥

Diberikan 2 List peserta webinar dari 2 sumber pendaftaran berikut (ada beberapa nama yang mendaftar dua kali):

```python
pendaftar_1 = ["Ana", "Budi", "Cici", "Dedi"]
pendaftar_2 = ["Cici", "Dedi", "Eni", "Fani"]
```

1. Ubah masing-masing List menjadi Set.
2. Tampilkan **gabungan (union)** semua peserta unik dari kedua sumber.
3. Tampilkan peserta yang **mendaftar di kedua sumber (irisan/intersection)**.
4. Tampilkan peserta yang **hanya ada di `pendaftar_1` saja (selisih/difference)**.
"""

pendaftar_1 = ["Ana", "Budi", "Cici", "Dedi"]
pendaftar_2 = ["Cici", "Dedi", "Eni", "Fani"]

# Jawaban Soal 6

# 1. Ubah masing-masing List menjadi Set.
set_1 = set(pendaftar_1)
set_2 = set(pendaftar_2)

# 2. Tampilkan gabungan (union)
peserta_unik = set_1 | set_2
print("Gabungan semua peserta unik:", peserta_unik)

# 3. Tampilkan peserta yang mendaftar di kedua sumber (irisan/intersection).
peserta_irisan = set_1 & set_2
print("Peserta yang mendaftar di kedua sumber:", peserta_irisan)

# 4. Tampilkan peserta yang hanya ada di pendaftar_1 saja (selisih/difference).
peserta_hanya_1 = set_1 - set_2
print("Peserta yang HANYA ada di pendaftar 1:", peserta_hanya_1)

