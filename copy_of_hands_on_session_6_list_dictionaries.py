#Selesai

"""---
# 🧮 Bagian 6 (Bonus): Operasi NumPy untuk Aljabar Linear

NumPy menyediakan operasi matriks siap pakai lewat modul `numpy.linalg`, yang menjadi dasar penting untuk *machine learning* dan *data science*.

| Operasi | Kode |
|---|---|
| Perkalian matriks | `A @ B` atau `np.dot(A, B)` |
| Transpose (baris ↔ kolom) | `A.T` |
| Determinan | `np.linalg.det(A)` |
| Invers matriks | `np.linalg.inv(A)` |
"""

import numpy as np

A = np.array([[1, 2], [3, 4]])
B = np.array([[5, 6], [7, 8]])

print("Perkalian matriks (A @ B):")
print(A @ B) #dot product

np.cross(A, B) #cross product

print("Transpose A (A.T):")
print(A.T)

print("Determinan A:")
print(np.linalg.det(A))

print("Invers matriks A:")
print(np.linalg.inv(A))

"""✏️ **Coba Sendiri:** Buat 2 matriks 2x2 sendiri (`C` dan `D`), lalu hitung hasil perkalian matriksnya (`C @ D`) dan transpose dari `C` (`C.T`)."""

# Tulis kodemu di sini
import numpy as np

C = np.array([[2, 1], [4, 3]])
D = np.array([[1, 0], [0, 2]])

print("Perkalian C @ D:")
print(C @ D)

print("\nTranspose dari C:")
print(C.T)

