"""---
# 🔢 Bagian 5 (Bonus): NumPy Array

Untuk data angka dalam jumlah besar, List biasa terasa lambat. **NumPy** adalah library Python yang menyediakan struktur data **array** yang jauh lebih cepat dan hemat memori untuk komputasi numerik.

> Jika belum terpasang, jalankan `!pip install numpy` terlebih dahulu di sel baru.
"""

import numpy as np

data = np.array([10, 20, 30, 40])

print(data)            # [10 20 30 40]
print(type(data))
print(data.shape)      # (4,)  -> artinya array 1 dimensi dengan 4 elemen

"""**Kelebihan utama NumPy** dibanding List biasa: operasi matematis bisa langsung diterapkan ke **semua elemen sekaligus** (disebut *vectorized operation*), tanpa perlu loop manual."""

data = np.array([10, 20, 30, 40])

print(data * 2)     # [20 40 60 80]   -> dikalikan 2 tanpa loop!
print(data + 5)     # [15 25 35 45]
print(data.sum())   # 100
print(data.mean())  # 25.0

# Bandingkan dengan cara List biasa (butuh loop / list comprehension):
data_list = [10, 20, 30, 40]
hasil = [x * 2 for x in data_list]
print(hasil)         # [20, 40, 60, 80]

"""NumPy array juga bisa berbentuk **matriks (2 dimensi)**:"""

matrix = np.array([[1, 2], [3, 4]])

print(matrix)
print(matrix.shape)   # (2, 2) -> 2 baris, 2 kolom

"""✏️ **Coba Sendiri:** Buat NumPy array berisi nilai ujian `[70, 85, 90, 60, 75]`, lalu hitung rata-rata (`.mean()`), nilai tertinggi (`.max()`), dan nilai terendah (`.min()`)."""

# Tulis kodemu di sini
import numpy as np

nilai_ujian = np.array([70, 85, 90, 60, 75])

print("Rata-rata:", nilai_ujian.mean())
print("Nilai tertinggi:", nilai_ujian.max())
