"""---
# 📖 Bagian 2: Dictionary

## 2.1 Apa itu Dictionary?

**Dictionary** menyimpan data berpasangan **key → value**, seperti kartu nama: setiap informasi (key) punya nilainya sendiri (value).

- Ditulis dengan kurung kurawal `{ }`
- Setiap pasangan ditulis `"key": value`
- **Key harus unik** (tidak boleh ada 2 key yang sama), tapi value boleh apa saja
"""

profil = {
    "nama": "Budi",
    "umur": 20,
    "kota": "Jakarta"
}

print(profil)
print(type(profil))

"""## 2.2 Mengakses Value lewat Key

Dictionary tidak diakses dengan nomor index, melainkan lewat **nama key**-nya.
"""

profil = {"nama": "Budi", "umur": 20}

print(profil["nama"])          # Budi

# Cara aman, tidak error jika key tidak ada
print(profil.get("kota"))      # None (karena key "kota" belum ada)

"""> ⚠️ **Hati-hati:** `profil["kota"]` akan menghasilkan `KeyError` jika key `"kota"` tidak ada. Gunakan `.get()` agar lebih aman.

## 2.3 Menambah & Mengubah Dictionary

- Jika key **sudah ada** → value diperbarui
- Jika key **belum ada** → key baru langsung ditambahkan
"""

profil = {"nama": "Budi", "umur": 20}

# Menambah key baru
profil["kota"] = "Jakarta"

# Mengubah value yang sudah ada
profil["umur"] = 21

print(profil)   # {'nama': 'Budi', 'umur': 21, 'kota': 'Jakarta'}

"""✏️ **Coba Sendiri:** Buat dictionary bernama `siswa` berisi `nama`, `kelas`, dan `nilai` milikmu (boleh rekaan). Lalu ubah nilai `nilai` menjadi 10 poin lebih tinggi."""

# Tulis kodemu di sini
siswa = {
    "nama": "Agil",
    "kelas": "Teknik Komputer",
    "nilai": 85
}

siswa["nilai"] += 10

print(siswa)

#Selesai

"""## 2.4 Iterasi Dictionary dengan Loop

Gunakan `.items()` untuk mengambil **key dan value sekaligus** di setiap perulangan.
"""

profil = {"nama": "Budi", "umur": 20, "kota": "Jakarta"}

for key, value in profil.items():
    print(key, "→", value)

"""## 2.5 List vs Dictionary — Kapan Pakai yang Mana?

| | **List** | **Dictionary** |
|---|---|---|
| Akses data | lewat index angka `list[0]` | lewat key/nama `dict["kunci"]` |
| Cocok untuk | data berurutan/sejenis | data berlabel/berpasangan |
| Contoh | daftar nilai, daftar belanja | profil siswa, data kontak |
| Sintaks | `nama = [item1, item2, ...]` | `nama = {"key": value}` |

## 2.6 Bonus: Kombinasi List & Dictionary

List dan Dictionary bisa digabung — List berisi banyak Dictionary. Ini sangat umum dipakai untuk menyimpan data banyak "record", misalnya data banyak siswa sekaligus.
"""

siswa = [
    {"nama": "Ana", "nilai": 90},
    {"nama": "Budi", "nilai": 85},
]

for s in siswa:
    print(s["nama"], s["nilai"])

"""---
# 🔒 Bagian 3 (Bonus): Tuple

**Tuple** mirip List, tapi datanya **terkunci** — tidak bisa diubah (*immutable*) setelah dibuat.

- Ditulis dengan kurung `( )`, bukan `[ ]`
- Cocok untuk data yang **harus tetap**, misalnya koordinat `(x, y)` atau kode warna RGB
"""

koordinat = (10, 20, 30)

print(koordinat[0])       # 10  -> tetap bisa diakses lewat index seperti List
print(len(koordinat))     # 3

# Mencoba mengubah isi tuple akan menghasilkan error
koordinat = (10, 20, 30)
koordinat[0] = 99   # ❌ Jalankan sel ini, perhatikan errornya!

"""> 🔎 Jalankan sel di atas — kamu akan melihat `TypeError: 'tuple' object does not support item assignment`. Itu **wajar**, karena memang itulah sifat utama Tuple: datanya tidak bisa diubah.

**List vs Tuple:**
- `List [ ]` → bisa diubah (*mutable*)
- `Tuple ( )` → tidak bisa diubah (*immutable*)

✏️ **Coba Sendiri:** Buat tuple bernama `rgb` berisi 3 angka (misalnya `(255, 0, 0)` untuk warna merah). Tampilkan item pertamanya dengan indexing.
"""

