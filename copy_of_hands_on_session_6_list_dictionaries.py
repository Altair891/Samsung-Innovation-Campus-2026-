"""---
# 🎯 Bagian 4 (Bonus): Set

**Set** menyimpan kumpulan data yang **unik** — otomatis tanpa duplikat, dan tanpa urutan yang tetap.

- Ditulis dengan kurung kurawal `{ }` (sama seperti Dictionary, tapi tanpa pasangan key-value)
"""

buah = {"apel", "jeruk", "apel", "mangga"}

print(buah)   # duplikat "apel" otomatis hilang!

buah = {"apel", "jeruk", "mangga"}

