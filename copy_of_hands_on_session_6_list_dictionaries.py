"""Set juga mendukung **operasi himpunan** matematika seperti irisan dan gabungan:"""

a = {1, 2, 3}
b = {2, 3, 4}

print(a & b)   # irisan (intersection)  -> {2, 3}
print(a | b)   # gabungan (union)       -> {1, 2, 3, 4}
print(a - b)   # selisih (difference)   -> {1}

"""✏️ **Coba Sendiri:** Buat sebuah List berisi angka dengan beberapa duplikat (misalnya `[1, 2, 2, 3, 3, 3]`), lalu ubah menjadi Set untuk menghilangkan duplikatnya. Petunjuk: gunakan `set(nama_list)`."""

# Tulis kodemu di sini
angka_duplikat = [1, 2, 2, 3, 3, 3]
angka_unik = set(angka_duplikat)

print("List awal:", angka_duplikat)
