"""## Soal 8 — NumPy Aljabar Linear: Operasi Matriks 🧮 (Tantangan)

Diberikan dua matriks berikut:

```python
M1 = np.array([[2, 0], [1, 3]])
M2 = np.array([[1, 4], [2, 1]])
```

1. Hitung dan tampilkan hasil perkalian matriks `M1 @ M2`.
2. Tampilkan transpose dari `M1`.
3. Hitung determinan dari `M1`.
4. Hitung invers dari `M1`.
5. **Tantangan tambahan**: Buktikan dengan kode bahwa `M1 @ np.linalg.inv(M1)` menghasilkan matriks identitas (mendekati `[[1, 0], [0, 1]]`).
"""

import numpy as np

M1 = np.array([[2, 0], [1, 3]])
M2 = np.array([[1, 4], [2, 1]])

# Jawaban Soal 8

# 1. Hitung dan tampilkan hasil perkalian matriks M1 @ M2.
hasil_kali = M1 @ M2
print("Hasil M1 @ M2:\n", hasil_kali)

# 2. Tampilkan transpose dari M1.
transpose_M1 = M1.T
print("\nTranspose dari M1:\n", transpose_M1)

# 3. Hitung determinan dari M1.
det_M1 = np.linalg.det(M1)
print("\nDeterminan M1:", det_M1)

# 4. Hitung invers dari M1.
invers_M1 = np.linalg.inv(M1)
print("\nInvers dari M1:\n", invers_M1)

# 5. Buktikan dengan kode bahwa M1 @ np.linalg.inv(M1) menghasilkan matriks identitas.
pembuktian = M1 @ invers_M1
print("\nPembuktian M1 dikali Invers M1 (Matriks Identitas):\n", pembuktian)

