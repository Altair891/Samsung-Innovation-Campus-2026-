"""## 5️⃣ Menulis ke File: Mode `"w"` vs `"a"`

- Mode **`"w"`** akan **menimpa** seluruh isi file yang lama
- Mode **`"a"`** akan **menambahkan** baris baru di akhir, isi lama tetap aman

Mari kita buktikan perbedaannya.
"""

# Mode "w" -> menimpa isi lama
with open("data_latihan/log.txt", "w") as file:
    file.write("Baris A")

with open("data_latihan/log.txt", "r") as file:
    print("Isi setelah mode w pertama kali:", file.read())

# Menulis LAGI dengan mode "w" -> isi lama HILANG, tertimpa total
with open("data_latihan/log.txt", "w") as file:
    file.write("Baris B")

with open("data_latihan/log.txt", "r") as file:
    print("Isi setelah mode w kedua kali:", file.read())
    print("⚠️  Perhatikan: 'Baris A' sudah hilang, tertimpa oleh 'Baris B'")

# Mode "a" -> menambah tanpa menghapus isi lama
with open("data_latihan/log.txt", "a") as file:
    file.write("\nBaris tambahan di akhir")

with open("data_latihan/log.txt", "r") as file:
    print("Isi setelah mode a:")
    print(file.read())
    print("✅ 'Baris B' masih ada, dan baris baru ditambahkan di bawahnya")

"""## 6️⃣ Apa itu CSV?

**CSV (Comma-Separated Values)** adalah cara menyimpan data tabel (seperti spreadsheet) dalam bentuk **teks murni**, di mana setiap kolom dipisahkan dengan tanda koma (`,`).

Contoh tabel:

| nama | usia | kota |
|------|------|------|
| Rani | 17 | Bandung |
| Budi | 16 | Jakarta |
| Sari | 17 | Surabaya |

Kalau ditulis dalam format CSV, jadinya seperti ini:

```
nama,usia,kota
Rani,17,Bandung
Budi,16,Jakarta
Sari,17,Surabaya
```

Baris pertama biasanya disebut **header** (nama kolom), dan baris-baris setelahnya adalah **data**.

Mari kita buat file CSV ini secara langsung dari Python.
"""

with open("data_latihan/siswa.csv", "w") as file:
    file.write("nama,usia,kota\n")
    file.write("Rani,17,Bandung\n")
    file.write("Budi,16,Jakarta\n")
    file.write("Sari,17,Surabaya\n")

print("File siswa.csv berhasil dibuat ✅")

with open("data_latihan/siswa.csv", "r") as file:
    print(file.read())

"""## 7️⃣ Membaca CSV dengan `split()`

Karena CSV hanyalah teks biasa dengan koma sebagai pemisah, kita bisa memecah setiap baris menjadi list menggunakan `split(",")`.

Alurnya:

```
"Rani,17,Bandung"  --split(",")-->  ["Rani", "17", "Bandung"]
```

> 💡 Kita juga memakai `.strip()` sebelum `.split()` untuk menghapus karakter enter (`\n`) di akhir baris.
"""

with open("data_latihan/siswa.csv", "r") as file:
    header = file.readline()  # lewati baris pertama (header)
    print("Header:", header.strip())
    print("---")
    for baris in file:
        data = baris.strip().split(",")
        print(data)

# Mengambil kolom tertentu saja, misalnya hanya nama dan kota
with open("data_latihan/siswa.csv", "r") as file:
    file.readline()  # lewati header
    for baris in file:
        data = baris.strip().split(",")
        nama = data[0]
        usia = data[1]
        kota = data[2]
        print(f"{nama} usia {usia} tinggal di {kota}")

